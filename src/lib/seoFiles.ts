/**
 * llms.txt follows the llmstxt.org shape: an H1, a blockquote summary, prose
 * with no headings, then H2 sections of links. Link descriptions are the same
 * strings the pages serve as their meta description, so an assistant and a
 * search engine are told the same thing about each page.
 */
export function llmsTxt(): string {
  const routes = indexableRoutes();
  const placed = new Set<string>(["/"]);

  const line = (route: RouteMetadata) => {
    placed.add(route.path);
    // The registry title carries the " | Aurixa Systems" suffix, which is
    // noise once the document is already headed "Aurixa Systems".
    const label = route.title.replace(/\s*\|\s*Aurixa Systems$/, "");
    return `- [${label}](${absoluteUrl(route.path)}): ${route.description}`;
  };

  const section = (heading: string, paths: string[]) => {
    const lines = paths
      .map((path) => routes.find((route) => route.path === path))
      .filter((route): route is RouteMetadata => route !== undefined)
      .map(line);
    return lines.length ? `## ${heading}\n${lines.join("\n")}\n` : "";
  };

  const curated = LLMS_SECTIONS.map(({ heading, paths }) => section(heading, paths));
  const optional = section("Optional", LLMS_OPTIONAL);
  const unplaced = routes.filter((route) => !placed.has(route.path)).map((route) => route.path);

  return [
    `# ${SITE_NAME}`,
    ``,
    `> ${DEFAULT_DESCRIPTION}`,
    ``,
    `${LEGAL_ENTITY.name} (ABN ${LEGAL_ENTITY.abn}) is based in ${LEGAL_ENTITY.location}.`,
    `Website: ${SITE_ORIGIN}/`,
    ``,
    `New customers start with a ${FREE_TRIAL_DAYS}-day free trial. The way in is an application`,
    `rather than self-serve sign-up, and the free trial page below is the entry`,
    `point. The Aurixa team reviews each application and provisions the customer's`,
    `own workspace; the trial runs for ${FREE_TRIAL_DAYS} days from the day that workspace goes`,
    `live. This guide does not cover pricing.`,
    ``,
    ...LLMS_OVERVIEW,
    ``,
    ...curated,
    section("Other pages", unplaced),
    optional,
  ]
    .join("\n")
    .replace(/\n{3,}/g, "\n\n");
}
